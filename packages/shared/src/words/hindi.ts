export function getHindiWord(num: number): HindiWordDetails {
  if (num < 1 || num > 90 || !Number.isInteger(num)) {
    throw new Error(`Invalid housie number: ${num}. Must be an integer between 1 and 90.`);
  }
  const details = HINDI_NUMBER_WORDS[num];
  if (!details) {
    throw new Error(`Missing Hindi word for number ${num}`);
  }
  return details;
}
